    function translatePage() {
        if (!document.documentElement.lang.startsWith('fr')) return;

        const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
        const nodes = [];
        while (walker.nextNode()) nodes.push(walker.currentNode);
        nodes.forEach((node) => {
            const value = node.nodeValue;
            const key = value.replace(/\s+/g, ' ').trim();
            if (!translations[key] || !key) return;
            node.nodeValue = value.replace(key, translations[key]);
        });

        document.querySelectorAll('input[placeholder], textarea[placeholder]').forEach((element) => {
            const key = element.getAttribute('placeholder');
            if (translations[key]) element.setAttribute('placeholder', translations[key]);
        });
        document.querySelectorAll('[title]').forEach((element) => {
            const key = element.getAttribute('title');
            if (translations[key]) element.setAttribute('title', translations[key]);
        });
    }

    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', translatePage);
    } else {
        translatePage();
    }
